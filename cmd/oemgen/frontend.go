package main

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"kandaoni.com/anqicms/config"
)

// frontendBrandPath 是前端品牌对象的生成位置。
//
// 生成物提交进仓库（与 provider/api_catalog.json 同理）：umi 的 dev/build 不该
// 依赖先跑一遍 Go 代码生成。为某个 OEM 构建后本文件会变成该品牌的版本，
// 属于预期的脏工作区，构建脚本结束时会提示用 git checkout 还原。
func frontendBrandPath(root string) string {
	return filepath.Join(root, "anqicms-admin", "src", "oem", "brand.ts")
}

// frontendAssetDir 是品牌图标在前端的位置。
//
// 放 src/ 而不是 public/，是为了能 `import` 成模块：umi 的 base 可能被
// window.APP_CONFIG 改成别的路径，写死 /oem/logo.svg 会 404；
// import 出来的地址由打包器按 publicPath 生成，两种情况都对。
func frontendAssetDir(root string) string {
	return filepath.Join(root, "anqicms-admin", "src", "oem", "assets")
}

func writeFrontendBrand(root string, b config.OEMBrand) error {
	out := frontendBrandPath(root)
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	logoFile, faviconFile, err := copyAssets(root, b)
	if err != nil {
		return err
	}

	var buf strings.Builder
	buf.WriteString("// Code generated by cmd/oemgen from config/oem/" + b.ID + "/brand.json. DO NOT EDIT.\n")
	buf.WriteString("//\n")
	buf.WriteString("// 改品牌请改 JSON 后运行 `go run ./cmd/oemgen -oem " + b.ID + "`。\n\n")
	// import 必须在最前面，所以先算好资源再拼文件。
	if logoFile != "" {
		buf.WriteString("import logoUrl from './assets/" + logoFile + "';\n")
	}
	if faviconFile != "" {
		buf.WriteString("import faviconUrl from './assets/" + faviconFile + "';\n")
	}
	if logoFile != "" || faviconFile != "" {
		buf.WriteString("\n")
	}

	buf.WriteString("export interface OEMBrand {\n")
	buf.WriteString("  id: string;\n")
	buf.WriteString("  /** 品牌主名（拉丁字母），用于 document.title 与 Logo alt */\n")
	buf.WriteString("  name: string;\n")
	buf.WriteString("  /** 中文名，为空时回退 name */\n")
	buf.WriteString("  nameCn: string;\n")
	buf.WriteString("  /** 版权持有方 */\n")
	buf.WriteString("  vendor: string;\n")
	buf.WriteString("  /** 官网 */\n")
	buf.WriteString("  website: string;\n")
	buf.WriteString("  /** 帮助文档根地址 */\n")
	buf.WriteString("  docs: string;\n")
	buf.WriteString("  /** 账号/授权/充值入口根地址 */\n")
	buf.WriteString("  authBase: string;\n")
	buf.WriteString("  /** 是否官方版：模板市场、官网账号绑定等入口仅官方版可见 */\n")
	buf.WriteString("  official: boolean;\n")
	buf.WriteString("  /** Logo 地址，空表示沿用官方内置图标 */\n")
	buf.WriteString("  logo: string;\n")
	buf.WriteString("  /** favicon 地址，空表示沿用官方图标 */\n")
	buf.WriteString("  favicon: string;\n")
	buf.WriteString("}\n\n")

	buf.WriteString("export const brand: OEMBrand = {\n")
	writeTSField(&buf, "id", b.ID)
	writeTSField(&buf, "name", b.Name)
	writeTSField(&buf, "nameCn", firstNonEmpty(b.NameCN, b.Name))
	writeTSField(&buf, "vendor", b.Vendor)
	writeTSField(&buf, "website", b.Website)
	writeTSField(&buf, "docs", b.Docs)
	writeTSField(&buf, "authBase", b.AuthBase)
	buf.WriteString("  official: " + strconv.FormatBool(b.ID == config.DefaultOEMID) + ",\n")
	buf.WriteString("  logo: " + tsIdentOrEmpty(logoFile, "logoUrl") + ",\n")
	buf.WriteString("  favicon: " + tsIdentOrEmpty(faviconFile, "faviconUrl") + ",\n")
	buf.WriteString("};\n\n")
	buf.WriteString("export default brand;\n")

	return os.WriteFile(out, []byte(buf.String()), 0o644)
}

// copyAssets 把 config/oem/<id>/assets/ 下的图标复制到前端 src/oem/assets/。
//
// 没有 assets 目录时保持官方图标不动：OEM 不强制换 logo，但一旦提供就必须
// 整体替换，否则会出现「图标是甲、标题是乙」这种最容易被客户截图的问题。
// 文件名决定用途（logo.* / favicon.*），不支持改约定 —— 约定不一致时
// 排查成本远高于省下的那点灵活性。
func copyAssets(root string, b config.OEMBrand) (logoFile, faviconFile string, err error) {
	srcDir := filepath.Join(root, "config", "oem", b.ID, "assets")
	entries, err := os.ReadDir(srcDir)
	if err != nil {
		if os.IsNotExist(err) {
			return "", "", nil
		}
		return "", "", err
	}
	dstDir := frontendAssetDir(root)
	if len(entries) > 0 {
		if err := os.MkdirAll(dstDir, 0o755); err != nil {
			return "", "", err
		}
	}
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		name := e.Name()
		if err := copyFile(filepath.Join(srcDir, name), filepath.Join(dstDir, name)); err != nil {
			return "", "", fmt.Errorf("复制品牌资源 %s 失败：%w", name, err)
		}
		switch {
		case strings.HasPrefix(name, "logo."):
			logoFile = name
		case strings.HasPrefix(name, "favicon."):
			faviconFile = name
		}
	}
	return logoFile, faviconFile, nil
}

func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.Create(dst)
	if err != nil {
		return err
	}
	defer out.Close()
	_, err = io.Copy(out, in)
	return err
}

// 前端统一两空格缩进 + 单引号：仓库里的 .ts 走 prettier 单引号风格，
// 生成物与手写文件风格不一致会在 review 里变成无意义的 diff。
func writeTSField(buf *strings.Builder, name, val string) {
	buf.WriteString("  " + name + ": " + quoteTS(val) + ",\n")
}

// tsIdentOrEmpty 有资源时引用 import 进来的地址，没有时给空串。
func tsIdentOrEmpty(file, ident string) string {
	if file == "" {
		return "''"
	}
	return ident
}

func quoteTS(s string) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, r := range s {
		switch r {
		case '\'':
			b.WriteString(`\'`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('\'')
	return b.String()
}

func firstNonEmpty(vals ...string) string {
	for _, v := range vals {
		if v != "" {
			return v
		}
	}
	return ""
}
